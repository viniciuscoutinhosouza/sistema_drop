-- 163_customer_credits.sql
-- ADR-0037: razão (ledger) de crédito do CLIENTE (comprador) por CMIG.
-- Terceiro razão de crédito do sistema — distinto do cmig_warehouse_credits (ADR-0034,
-- CMIG×Galpão) e do ACProfile.balance. Aqui o saldo é um PASSIVO com o cliente final:
-- quando um pedido PAGO é cancelado, cria-se um 'credit' = valor pago, para o operador
-- depois devolver o dinheiro (ou abater numa compra futura) lançando um 'debit'.
-- Saldo = Σ créditos − Σ débitos por (cmig_id, person_id). Append-only (sem UPDATE/DELETE).
-- Escopo por CMIG/Galpão (ADR-0026). Idempotente (ORA-00955 objeto).

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE customer_credits (
      id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      cmig_id     NUMBER NOT NULL REFERENCES cmigs(id),
      person_id   NUMBER NOT NULL REFERENCES people(id),
      entry_type  VARCHAR2(10) NOT NULL,
      amount      NUMBER(15,2) NOT NULL,
      order_id    NUMBER REFERENCES orders(id),
      description VARCHAR2(500),
      created_by  NUMBER REFERENCES users(id),
      created_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP
    )';
EXCEPTION
  WHEN e_obj_exists THEN NULL;
END;
/

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE
    'CREATE INDEX idx_customer_credit ON customer_credits (cmig_id, person_id)';
EXCEPTION
  WHEN e_obj_exists THEN NULL;
END;
/
