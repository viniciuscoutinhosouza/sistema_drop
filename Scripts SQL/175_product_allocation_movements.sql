-- Migration 175: Razão append-only de movimentos de ENDEREÇO — Endereçamento Fase 2.5 (ADR-0039).
-- Registra o débito do endereço ao despachar (confirm_dispatch) e o crédito no retorno ao vendável
-- (confirm_pending_return / validate_return_items aprovado). É o espelho de stock_movements × qty_units:
--   stock_movements  → stock_quantity (SSOT escalar, ADR-0004)
--   product_allocation_movements → product_allocations.qty_units (camada de LOCALIZAÇÃO, ADR-0039)
-- A camada de endereço NUNCA grava saldo escalar; o débito/crédito só move qty_units e loga aqui.
--
-- Colunas-chave:
--   order_id / return_id       = âncora de idempotência (dispatch por order_id; crédito por return_id)
--   allocation_id / location_id / lot_id = o que de fato foi debitado (fidelidade de local/lote p/ recall)
--   base_product_type/_id      = o produto-LÓGICO (pg|cmig base) — bridge p/ o crédito do retorno, que é
--                                base-level, reencontrar os débitos feitos no nível de VARIANTE
--   product_type/_id           = o tipo/id da ALOCAÇÃO de fato (pode ser variant_pg/variant_cmig)
--   delta_units                = negativo no débito (dispatch), positivo no crédito (return)
--   reason                     = 'dispatch' | 'return'
-- Idempotente: cada DDL em bloco próprio tratando ORA-00955 (objeto existe).

-- ── product_allocation_movements ─────────────────────────────────────────────
DECLARE
  e_obj_exists EXCEPTION; PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE product_allocation_movements (
      id                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      warehouse_id       NUMBER NOT NULL REFERENCES warehouses(id),
      order_id           NUMBER REFERENCES orders(id),
      return_id          NUMBER REFERENCES returns(id),
      allocation_id      NUMBER REFERENCES product_allocations(id),
      location_id        NUMBER REFERENCES storage_locations(id),
      product_type       VARCHAR2(20) NOT NULL,
      product_id         NUMBER NOT NULL,
      base_product_type  VARCHAR2(20) NOT NULL,
      base_product_id    NUMBER NOT NULL,
      lot_id             NUMBER REFERENCES product_lots(id),
      delta_units        NUMBER NOT NULL,
      reason             VARCHAR2(20) NOT NULL,
      created_by         NUMBER REFERENCES users(id),
      created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
      CONSTRAINT ck_palloc_mov_reason CHECK (reason IN (''dispatch'',''return''))
    )';
EXCEPTION WHEN e_obj_exists THEN NULL;
END;
/

