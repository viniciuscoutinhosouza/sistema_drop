-- 153_asaas_payment_charges.sql
-- Fase 2 (ADR-0032): integração ASAAS — cobrança da venda manual pela conta do Galpão.
--  (a) coluna webhook_token_hash em warehouse_bank_accounts: SHA-256 do authToken do webhook
--      daquela conta ASAAS (nunca o token em claro) — valida o header asaas-access-token.
--  (b) tabela payment_charges: cobranças criadas no ASAAS, ligando cobrança↔pedido↔galpão.
-- Idempotente (ORA-01430 coluna / ORA-00955 objeto).

DECLARE
  e_col_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_col_exists, -1430);
BEGIN
  EXECUTE IMMEDIATE
    'ALTER TABLE warehouse_bank_accounts ADD (webhook_token_hash VARCHAR2(64))';
EXCEPTION
  WHEN e_col_exists THEN NULL;
END;
/

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE payment_charges (
      id                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      warehouse_id       NUMBER NOT NULL REFERENCES warehouses(id),
      bank_account_id    NUMBER NOT NULL REFERENCES warehouse_bank_accounts(id) ON DELETE CASCADE,
      order_id           NUMBER REFERENCES orders(id),
      provider           VARCHAR2(20) DEFAULT ''asaas'' NOT NULL,
      asaas_customer_id  VARCHAR2(60),
      asaas_payment_id   VARCHAR2(60) NOT NULL CONSTRAINT uq_pay_charge_asaas_id UNIQUE,
      billing_type       VARCHAR2(20),
      value              NUMBER(15,2),
      status             VARCHAR2(30),
      invoice_url        VARCHAR2(500),
      bank_slip_url      VARCHAR2(500),
      pix_payload        VARCHAR2(2000),
      due_date           DATE,
      external_reference VARCHAR2(100),
      created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
      updated_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP
    )';
EXCEPTION
  WHEN e_obj_exists THEN NULL;
END;
/

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE
    'CREATE INDEX idx_pay_charge_order ON payment_charges (order_id)';
EXCEPTION
  WHEN e_obj_exists THEN NULL;
END;
/
