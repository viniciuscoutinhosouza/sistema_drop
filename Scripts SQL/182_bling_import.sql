-- 182_bling_import.sql
-- Fase 2 do Bling (ADR-0040): importar categorias/produtos/kits do Bling -> CMIG ou PG.
-- (1) rastreio da origem Bling p/ dedup + re-sync (idempotência): bling_product_id em cmig_products
--     E em catalog_products (a coluna NÃO existia — a de dropshipper_products é outra tabela),
--     bling_category_id em categories.
-- (2) tabela de JOB de importação assíncrono (molde competitor_analyses / ADR-0011).
-- Idempotente: ORA-01430 (coluna já existe), ORA-00955 (objeto já existe).

-- bling_product_id em cmig_products
DECLARE
  e_col EXCEPTION; PRAGMA EXCEPTION_INIT(e_col, -1430);
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE cmig_products ADD (bling_product_id VARCHAR2(40))';
EXCEPTION WHEN e_col THEN NULL;
END;
/
-- bling_product_id em catalog_products (PG) — a coluna NÃO existia (a homônima é de dropshipper_products)
DECLARE
  e_col EXCEPTION; PRAGMA EXCEPTION_INIT(e_col, -1430);
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE catalog_products ADD (bling_product_id VARCHAR2(40))';
EXCEPTION WHEN e_col THEN NULL;
END;
/
-- bling_category_id em categories
DECLARE
  e_col EXCEPTION; PRAGMA EXCEPTION_INIT(e_col, -1430);
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE categories ADD (bling_category_id VARCHAR2(40))';
EXCEPTION WHEN e_col THEN NULL;
END;
/
-- índices de busca por origem Bling (dedup/re-sync). ORA-00955 se já existir.
DECLARE
  e_obj EXCEPTION; PRAGMA EXCEPTION_INIT(e_obj, -955);
BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX ix_cmig_prod_bling ON cmig_products (cmig_id, bling_product_id)';
EXCEPTION WHEN e_obj THEN NULL;
END;
/
DECLARE
  e_obj EXCEPTION; PRAGMA EXCEPTION_INIT(e_obj, -955);
BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX ix_catalog_prod_bling ON catalog_products (bling_product_id)';
EXCEPTION WHEN e_obj THEN NULL;
END;
/
-- Tabela de JOB de importação (assíncrono, progresso + contadores).
DECLARE
  e_obj EXCEPTION; PRAGMA EXCEPTION_INIT(e_obj, -955);
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE bling_import_jobs (
      id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      cmig_id           NUMBER NOT NULL REFERENCES cmigs(id),
      target            VARCHAR2(10) NOT NULL,        -- cmig | pg
      on_conflict       VARCHAR2(10) NOT NULL,        -- skip | update
      options_json      CLOB,                          -- seleção/opções (imagens, kits, fiscal)
      status            VARCHAR2(20) DEFAULT ''running'' NOT NULL,  -- running|done|error|cancelled
      progress_step     VARCHAR2(200),
      total             NUMBER DEFAULT 0 NOT NULL,
      created_count     NUMBER DEFAULT 0 NOT NULL,
      updated_count     NUMBER DEFAULT 0 NOT NULL,
      skipped_count     NUMBER DEFAULT 0 NOT NULL,
      failed_count      NUMBER DEFAULT 0 NOT NULL,
      result_json       CLOB,                          -- erros por item + resumo
      error             VARCHAR2(2000),
      requested_by      NUMBER REFERENCES users(id),
      created_at        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
      finished_at       TIMESTAMP WITH TIME ZONE
    )';
EXCEPTION WHEN e_obj THEN NULL;
END;
/
