-- 179_bling_accounts.sql
-- Integração Bling (ERP) por CMIG via OAuth2 (Bling API v3). Guarda a conexão de UMA CMIG com a
-- conta Bling dela: access_token/refresh_token CIFRADOS (Fernet), validade, escopo, empresa Bling
-- e estado. UMA conexão por CMIG (UNIQUE cmig_id) — a reconexão faz UPDATE in-place.
-- Molde: 167_google_drive_accounts.sql (ADR-0038). Tokens em CLOB (Bling migra token opaco → JWT,
-- que pode passar de VARCHAR2(4000)). Idempotente (ORA-00955 objeto já existe).

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE cmig_bling_accounts (
      id                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      cmig_id              NUMBER NOT NULL REFERENCES cmigs(id),
      access_token_enc     CLOB,
      refresh_token_enc    CLOB,
      token_expires_at     TIMESTAMP WITH TIME ZONE,
      scope                VARCHAR2(500),
      bling_company_id     VARCHAR2(100),
      bling_company_name   VARCHAR2(255),
      connected_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
      last_used_at         TIMESTAMP WITH TIME ZONE,
      last_error           VARCHAR2(1000),
      connected_by_user_id NUMBER REFERENCES users(id),
      CONSTRAINT uq_bling_cmig UNIQUE (cmig_id)
    )';
EXCEPTION
  WHEN e_obj_exists THEN NULL;
END;
/
