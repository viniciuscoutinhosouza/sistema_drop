-- 155_cmig_warehouse_credits.sql
-- Fase 4 (ADR-0034): razão (ledger) de crédito CMIG × Galpão.
-- A venda de PG precisa estar paga OU coberta por crédito que a CMIG deixou com o Galpão antes
-- da entrega (flag warehouses.pg_requires_prepaid, Fase 1). Cada linha é um movimento:
--   entry_type 'credit' (CMIG depositou crédito no Galpão) | 'debit' (consumo por venda PG).
-- Saldo = Σ créditos − Σ débitos por (cmig_id, warehouse_id). Append-only (sem UPDATE/DELETE).
-- Idempotente (ORA-00955 objeto).

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE cmig_warehouse_credits (
      id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      cmig_id      NUMBER NOT NULL REFERENCES cmigs(id),
      warehouse_id NUMBER NOT NULL REFERENCES warehouses(id),
      entry_type   VARCHAR2(10) NOT NULL,
      amount       NUMBER(15,2) NOT NULL,
      order_id     NUMBER REFERENCES orders(id),
      description  VARCHAR2(500),
      created_by   NUMBER REFERENCES users(id),
      created_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP
    )';
EXCEPTION
  WHEN e_obj_exists THEN NULL;
END;
/

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE
    'CREATE INDEX idx_cmig_wh_credit ON cmig_warehouse_credits (cmig_id, warehouse_id)';
EXCEPTION
  WHEN e_obj_exists THEN NULL;
END;
/
