      warehouse_id       NUMBER NOT NULL REFERENCES warehouses(id) ON DELETE CASCADE,
      provider           VARCHAR2(20) DEFAULT ''asaas'' NOT NULL,
      bank_code          VARCHAR2(10),
      name               VARCHAR2(200) NOT NULL,
      api_key_encrypted  VARCHAR2(2000),
      wallet_id          VARCHAR2(100),
      chart_account_label VARCHAR2(255),
      is_sandbox         NUMBER(1) DEFAULT 0 NOT NULL,
      is_active          NUMBER(1) DEFAULT 1 NOT NULL,
      is_primary         NUMBER(1) DEFAULT 0 NOT NULL,
      agency             VARCHAR2(20),
      account_number     VARCHAR2(30),
      pix_key_type       VARCHAR2(20),
      pix_key            VARCHAR2(255),
      holder_name        VARCHAR2(255),
      holder_document    VARCHAR2(20),
      opening_balance    NUMBER(15,2) DEFAULT 0,
      opening_balance_date DATE,
      notes              VARCHAR2(2000),
      created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
      updated_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP
