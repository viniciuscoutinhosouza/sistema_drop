-- Fase 1 do checkout/recebimento por Galpão (ADR-0031):
--  (a) 2 flags de config no Galpão:
--      pg_requires_prepaid          = venda de PG exige a CMIG ter crédito/pagar antes da entrega
--      manual_sale_requires_payment = venda manual exige pagamento do cliente p/ dar continuidade
--      (ambas INERTES na Fase 1 — só capturam a config; o enforcement entra nas fases 2-4)
--  (b) tabela warehouse_bank_accounts: contas de recebimento por Galpão (ex.: ASAAS), com a
--      API Key CIFRADA (Fernet, services/crypto) — nunca em claro.
-- Idempotente (ORA-01430 coluna / ORA-00955 objeto).

DECLARE
  e_col_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_col_exists, -1430);
