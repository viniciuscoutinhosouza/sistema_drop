-- 169_order_payment_proofs.sql
-- Trilha append-only de confirmação/cancelamento MANUAL de pagamento do pedido (comprovante no
-- Google Drive, ADR-0038). Complementa o ASAAS. Idempotente (ORA-00955).

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE order_payment_proofs (
      id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      order_id       NUMBER NOT NULL REFERENCES orders(id),
      event_type     VARCHAR2(10) NOT NULL,
      payment_method VARCHAR2(50),
      description    VARCHAR2(1000),
      proof_drive_id VARCHAR2(100),
      reason         VARCHAR2(1000),
      created_by     NUMBER REFERENCES users(id),
      created_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP
    )';
EXCEPTION
  WHEN e_obj_exists THEN NULL;
END;
/

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX idx_order_pay_proof ON order_payment_proofs (order_id, id)';
EXCEPTION
  WHEN e_obj_exists THEN NULL;
END;
/
