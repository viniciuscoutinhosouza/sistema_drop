-- 167_google_drive_accounts.sql
-- Integração Google Drive (armazenamento de imagens, OAuth2 drive.file). Guarda a conexão:
-- refresh_token CIFRADO (Fernet), access_token curto, pasta raiz e estado. Uma ativa por vez.
-- Idempotente (ORA-00955 objeto já existe).

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE google_drive_accounts (
      id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email             VARCHAR2(255),
      refresh_token_enc CLOB NOT NULL,
      access_token      CLOB,
      expires_at        TIMESTAMP WITH TIME ZONE,
      root_folder_id    VARCHAR2(100),
      root_folder_name  VARCHAR2(255),
      scope             VARCHAR2(300),
      is_active         NUMBER DEFAULT 1 NOT NULL,
      connected_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
      last_used_at      TIMESTAMP WITH TIME ZONE,
      last_error        VARCHAR2(1000),
      created_by        NUMBER REFERENCES users(id),
      CONSTRAINT ck_gdrive_active CHECK (is_active IN (0, 1))
    )';
EXCEPTION
  WHEN e_obj_exists THEN NULL;
END;
/
