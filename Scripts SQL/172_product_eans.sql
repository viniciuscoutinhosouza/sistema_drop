-- 172_product_eans.sql
-- Multi-EAN por produto (CMIG e PG): um produto pode ter 1+ EANs. O EAN principal segue na coluna
-- .ean do produto; EANs ADICIONAIS ficam aqui. Usado p/ reconciliar NF-e de entrada cujo EAN não
-- bate com o cadastro, sem perder o EAN principal. Casamento de estoque (3 superfícies) passa a
-- consultar também esta tabela. Idempotente (ORA-00955 objeto já existe).

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE product_eans (
      id                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      cmig_product_id    NUMBER REFERENCES cmig_products(id),
      catalog_product_id NUMBER REFERENCES catalog_products(id),
      ean                VARCHAR2(14) NOT NULL,
      created_by         NUMBER REFERENCES users(id),
      created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
      CONSTRAINT ck_product_eans_one_fk CHECK (
        (CASE WHEN cmig_product_id IS NULL THEN 0 ELSE 1 END)
        + (CASE WHEN catalog_product_id IS NULL THEN 0 ELSE 1 END) = 1
      )
    )';
EXCEPTION
  WHEN e_obj_exists THEN NULL;
END;
/

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX ix_product_eans_ean ON product_eans(ean)';
EXCEPTION WHEN e_obj_exists THEN NULL;
END;
/

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX ix_product_eans_cmig ON product_eans(cmig_product_id)';
EXCEPTION WHEN e_obj_exists THEN NULL;
END;
/

DECLARE
  e_obj_exists EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_obj_exists, -955);
BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX ix_product_eans_cat ON product_eans(catalog_product_id)';
EXCEPTION WHEN e_obj_exists THEN NULL;
END;
/
